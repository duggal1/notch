// PixelIcon.tsx — hand-authored 12px bitmap icons on the 12px integer grid.
// No stocks, no strokes, no anti-aliasing. Each row must be exactly 12 chars; sizes are integer
// multiples of 12. Icon references everywhere use the same names the rail and other components do.
const I = (rows: string[]) => {
  // Author at 12px; normalize defensively to exactly 12 wide.
  return rows.map((r) => (r.length >= 12 ? r.slice(0, 12) : r.padEnd(12, '.')));
};

