export type PixelIconName = keyof typeof PIXEL_ICONS;

// Build-time contract: every bitmap is exactly 12x12. A malformed row is a bug, not a style choice.
for (const [name, rows] of Object.entries(PIXEL_ICONS)) {
  if (rows.length !== 12 || rows.some((row) => row.length !== 12)) {
    throw new Error(`PixelIcon "${name}" must be 12 rows of 12 cells`);
  }
}

const runs = (rows: readonly string[]) =>
  rows.flatMap((row, y) => [...row.matchAll(/#+/g)].map((m) => ({ x: m.index!, y, w: m[0].length })));

export function PixelIcon({ name, size = 24, className }: { name: PixelIconName; size?: 12 | 24 | 36; className?: string }) {
  return (
    <svg width={size} height={size} viewBox="0 0 12 12" shapeRendering="crispEdges"
      fill="currentColor" aria-hidden="true" focusable="false" className={className}>
      {runs(PIXEL_ICONS[name]).map((r, i) => <rect key={i} x={r.x} y={r.y} width={r.w} height={1} />)}
    </svg>
  );
}
