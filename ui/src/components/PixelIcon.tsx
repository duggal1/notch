export type PixelIconName = keyof typeof PIXEL_ICONS;

export function PixelIcon({ name, size = 24, className }: { name: PixelIconName; size?: 12 | 24 | 36; className?: string }) {
  return (
    <svg width={size} height={size} viewBox="0 0 12 12" shapeRendering="crispEdges"
      fill="currentColor" aria-hidden="true" focusable="false" className={className}>
      {PIXEL_ICONS[name].flatMap((row, y) =>
        [...row.matchAll(/#+/g)].map((m, i) =>
          <rect key={`${i}-${y}`} x={(m.index ?? 0)} y={y} width={m[0].length} height={1} />))}
    </svg>
  );
}
