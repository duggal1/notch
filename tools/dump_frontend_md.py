#!/usr/bin/env python3
"""Copy only real, hand-authored frontend UI source into one Markdown document.

Included: ui/src/** UI components, UI logic/wiring, and styles (.tsx, .ts, .css).
Excluded on purpose: package.json / package-lock.json, tsconfig, vite.config,
index.html scaffold, test harnesses, .d.ts shims, design docs, generated dirs.

Usage:
  python3 tools/dump_frontend_md.py                 # writes docs/frontend.md
  python3 tools/dump_frontend_md.py --out X.md      # custom output
  python3 tools/dump_frontend_md.py --verify        # re-read output, check every sha256 against source

Stdlib only. Every section is the verbatim file content inside a fenced code block.
"""
import argparse
import hashlib
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
DEFAULT_SOURCE = ROOT / "ui"
DEFAULT_OUT = ROOT / "docs" / "frontend.md"
SKIP_DIRS = {"node_modules", "dist"}
UI_SUFFIXES = {".tsx", ".ts", ".css"}
NOT_UI_CODE = {"testkit.ts", "vite-env.d.ts"}   # harness + generated type shim
LANG = {".ts": "ts", ".tsx": "tsx", ".css": "css", ".json": "json",
        ".html": "html", ".mjs": "js", ".js": "js", ".md": "markdown",
        ".yaml": "yaml", ".yml": "yaml", ".sh": "bash"}


def source_files(source: pathlib.Path):
    # Real UI code lives in ui/src/. If a caller passes ui/ itself, descend into src/.
    base = source / "src" if (source / "src").is_dir() else source
    files = sorted(p for p in base.rglob("*")
                   if p.is_file()
                   and p.suffix in UI_SUFFIXES
                   and p.name not in NOT_UI_CODE
                   and not (set(p.relative_to(base).parts) & SKIP_DIRS))
    text, binary = [], []
    for p in files:
        try:
            p.read_text(encoding="utf-8")
            text.append(p)
        except UnicodeDecodeError:
            binary.append(p)
    return text, binary


def fence_for(content: str) -> str:
    n = 3
    while "`" * n in content:
        n += 1
    return "`" * n


def build(source: pathlib.Path) -> str:
    text, binary = source_files(source)
    lines = [
        "# Notch frontend — verbatim source dump",
        "",
        f"Source directory: `{source.relative_to(ROOT) if source.is_relative_to(ROOT) else source}`.",
        f"Generated by `tools/dump_frontend_md.py` — {len(text)} hand-authored UI files "
        "(components, logic, styles). Every section is the exact file content; "
        "`sha256` lines are for verification.",
        "",
        "## Contents",
        "",
    ]
    for p in text:
        rel = p.relative_to(ROOT).as_posix()
        lines.append(f"- [{rel}](#{rel.replace('/', '-').replace('.', '')})")
    lines.append("")
    for p in text:
        rel = p.relative_to(ROOT).as_posix()
        content = p.read_text(encoding="utf-8")
        digest = hashlib.sha256(p.read_bytes()).hexdigest()
        fence = fence_for(content)
        lang = LANG.get(p.suffix.lower(), "")
        lines += [
            f"## {rel}",
            "",
            f"sha256: `{digest}` · bytes: `{p.stat().st_size}`",
            "",
            f"{fence}{lang}",
            content.rstrip("\n"),
            fence,
            "",
            "",
        ]
    if binary:
        lines += ["## Skipped binary files", ""]
        for p in binary:
            lines.append(f"- `{p.relative_to(ROOT).as_posix()}` ({p.stat().st_size} bytes)")
        lines.append("")
    return "\n".join(lines)


def verify(source: pathlib.Path, out: pathlib.Path) -> bool:
    doc = out.read_text(encoding="utf-8")
    text, _ = source_files(source)
    ok = True
    for p in text:
        digest = hashlib.sha256(p.read_bytes()).hexdigest()
        if f"sha256: `{digest}` · bytes: `{p.stat().st_size}`" not in doc:
            print(f"MISMATCH: {p.relative_to(ROOT).as_posix()}", file=sys.stderr)
            ok = False
    print(f"verified {len(text)} sections" if ok else "verification FAILED")
    return ok


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--source", type=pathlib.Path, default=DEFAULT_SOURCE)
    ap.add_argument("--out", type=pathlib.Path, default=DEFAULT_OUT)
    ap.add_argument("--verify", action="store_true")
    args = ap.parse_args()
    if args.verify:
        return 0 if verify(args.source, args.out) else 1
    doc = build(args.source)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(doc, encoding="utf-8")
    text, binary = source_files(args.source)
    print(f"wrote {args.out} · {len(text)} files · {len(doc.encode())} bytes · {len(binary)} binary skipped")
    return 0


if __name__ == "__main__":
    sys.exit(main())
